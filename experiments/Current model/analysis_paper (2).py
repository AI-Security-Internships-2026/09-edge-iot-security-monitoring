@dataclass
class RunRecord:
    """One (E#, seed, condition_tag) run directory, fully parsed."""
    experiment: str
    seed: int
    condition_tag: str
    run_dir: str
    manifest: dict = field(default_factory=dict)
    final_test: dict = field(default_factory=dict)     # single row, flat dict
    dp_final_epsilon: dict = field(default_factory=dict)  # {client_id: eps}
    krum_rows: "pd.DataFrame" = None                    # per_client_krum_scores, or None
    runtime: dict = field(default_factory=dict)         # {latency_sec_per_round, peak_ram_mb, comms_bytes} or {} (E8 only)

    # Convenience accessors -- all read from the manifest, NEVER from
    # condition_tag string parsing (see module docstring).
    @property
    def aggregator(self):
        return self.manifest.get("aggregator")

    @property
    def alpha(self):
        return self.manifest.get("alpha_dirichlet")

    @property
    def attack_type(self):
        return self.manifest.get("attack_type")

    @property
    def byzantine_attack(self):
        return self.manifest.get("byzantine_attack")

    @property
    def target_epsilon(self):
        return self.manifest.get("dp_full_run_target_epsilon")

    @property
    def use_dp(self):
        return self.manifest.get("use_dp")

    @property
    def fedprox_mu(self):
        return self.manifest.get("prox_mu")

    @property
    def num_byzantine(self):
        return self.manifest.get("num_byzantine")

    @property
    def krum_k(self):
        return self.manifest.get("adaptive_krum_k")

    @property
    def final_total_epsilon_mean(self):
        if not self.dp_final_epsilon:
            return None
        vals = list(self.dp_final_epsilon.values())
        return float(np.mean(vals)) if vals else None


def load_manifest(run_dir):
    # experiment_config_*.json is disambiguated from dp_final_epsilon_*
    # .json (both are *.json in the same directory) by prefix, not by
    # _find_one's generic single-match-per-suffix assumption -- that
    # assumption doesn't hold for ".json" specifically since two
    # different output file KINDS share the extension.
    candidates = [f for f in os.listdir(run_dir)
                  if f.startswith("experiment_config_") and f.endswith(".json")] \
        if os.path.isdir(run_dir) else []
    if len(candidates) != 1:
        return None
    with open(os.path.join(run_dir, candidates[0])) as f:
        return json.load(f)


def load_final_test(run_dir):
    candidates = [f for f in os.listdir(run_dir)
                  if f.endswith("_FINAL_TEST.csv")] if os.path.isdir(run_dir) else []
    if len(candidates) != 1:
        return None
    with open(os.path.join(run_dir, candidates[0]), newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
    if len(rows) != 1:
        print(f"  WARNING: expected exactly 1 row in {candidates[0]} "
              f"({run_dir}), found {len(rows)} -- skipping.")
        return None
    row = rows[0]
    out = {}
    for k, v in row.items():
        try:
            out[k] = float(v)
        except (TypeError, ValueError):
            out[k] = v  # non-numeric fields (model_type, ablation_mode, ...)
    return out


def load_dp_final_epsilon(run_dir):
    candidates = [f for f in os.listdir(run_dir)
                  if f.startswith("dp_final_epsilon_") and f.endswith(".json")] \
        if os.path.isdir(run_dir) else []
    if len(candidates) != 1:
        return {}
    with open(os.path.join(run_dir, candidates[0])) as f:
        data = json.load(f)
    return {int(k): float(v) for k, v in
            data.get("final_total_epsilon_by_client", {}).items()}


def load_krum_rows(run_dir):
    candidates = [f for f in os.listdir(run_dir)
                  if f.startswith("per_client_krum_scores_") and f.endswith(".csv")] \
        if os.path.isdir(run_dir) else []
    if len(candidates) != 1:
        return None
    df = pd.read_csv(os.path.join(run_dir, candidates[0]))
    return df


def load_runtime(run_dir):
    """
    FIX: table_5_runtime_overhead() always reported "E8 data found but
    missing columns" -- confirmed via a real E8 run that
    run_campaign.py's _write_runtime_csv() DOES correctly write
    runtime_<TAG>.csv with exactly latency_sec_per_round, peak_ram_mb,
    comms_bytes -- but discover_runs()/RunRecord/build_master_dataframe()
    never read that file at all (it's not in the module docstring's
    INPUT LAYOUT list, and no load_* function here loaded it). The gap
    was entirely on this script's reading side, not in what
    run_campaign.py produces. This mirrors load_krum_rows()'s pattern:
    a single runtime_*.csv candidate per run_dir, returned as a
    {column: value} dict (single-row file -- unlike krum_rows, which is
    genuinely per-round/per-client and stays a full DataFrame) so
    build_master_dataframe() can merge it directly into the row dict.
    """
    candidates = [f for f in os.listdir(run_dir)
                  if f.startswith("runtime_") and f.endswith(".csv")] \
        if os.path.isdir(run_dir) else []
    if len(candidates) != 1:
        return {}
    with open(os.path.join(run_dir, candidates[0]), newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
    if len(rows) != 1:
        print(f"  WARNING: expected exactly 1 row in {candidates[0]} "
              f"({run_dir}), found {len(rows)} -- skipping runtime data "
              f"for this run.")
        return {}
    out = {}
    for k, v in rows[0].items():
        try:
            out[k] = float(v)
        except (TypeError, ValueError):
            out[k] = v
    return out


def discover_runs(results_root):
    """Walk experiments/results/<E#>/<seed>/<condition_tag>/ and load
    every run found. Skips (with a printed reason) any directory
    missing a manifest -- a run that hasn't finished, or isn't a run
    directory at all, rather than crashing the whole pipeline."""
    runs = []
    if not os.path.isdir(results_root):
        print(f"  WARNING: results root {results_root!r} does not exist "
              f"-- no data to analyze yet (this is expected before "
              f"Task 3's campaign has been run).")
        return runs

    for experiment in sorted(os.listdir(results_root)):
        exp_dir = os.path.join(results_root, experiment)
        if not os.path.isdir(exp_dir):
            continue
        for seed_dir_name in sorted(os.listdir(exp_dir)):
            seed_dir = os.path.join(exp_dir, seed_dir_name)
            if not os.path.isdir(seed_dir):
                continue
            try:
                seed = int(seed_dir_name)
            except ValueError:
                print(f"  WARNING: {seed_dir} is not a seed-numbered "
                      f"directory (expected an int name) -- skipping.")
                continue
            for condition_tag in sorted(os.listdir(seed_dir)):
                run_dir = os.path.join(seed_dir, condition_tag)
                if not os.path.isdir(run_dir):
                    continue
                manifest = load_manifest(run_dir)
                if manifest is None:
                    print(f"  SKIP (no manifest yet): {run_dir}")
                    continue
                final_test = load_final_test(run_dir) or {}
                dp_eps = load_dp_final_epsilon(run_dir)
                krum_rows = load_krum_rows(run_dir)
                runtime = load_runtime(run_dir)
                runs.append(RunRecord(
                    experiment=experiment, seed=seed, condition_tag=condition_tag,
                    run_dir=run_dir, manifest=manifest, final_test=final_test,
                    dp_final_epsilon=dp_eps, krum_rows=krum_rows, runtime=runtime,
                ))
    print(f"  Discovered {len(runs)} completed run(s) under {results_root!r}.")
    return runs


def class_names_from_runs(runs):
    """Recover the real class names from FINAL_TEST_CSV's own header
    (columns named test_f1_<name>) rather than hardcoding a class list
    that could silently drift from data_loader.py's actual label set.

    NOTE: this list is alphabetically sorted for stable, deterministic
    iteration/display order elsewhere in this script (e.g. Figure 6's
    axis ordering when passed the full list) -- it is NOT a rarity
    ordering. Do not slice this with [:n] to get "the n rarest classes"
    -- see select_rare_classes() below, which is what Task 5/6 and
    Figure 6 actually use for that purpose."""
    names = set()
    for r in runs:
        for k in r.final_test:
            if k.startswith("test_f1_") and k not in ("test_f1_macro",):
                names.add(k[len("test_f1_"):])
    return sorted(names)


