def table_2_aggregator_comparison(df, registry, mode, tables_dir):
    """Table 2 -- E2 aggregator x attack-family comparison. Headline
    paired test: Calibrated Krum vs the best non-calibrated baseline
    aggregator (whichever of {adaptive_krum, multi_krum, median,
    trimmed_mean} has the highest mean Byzantine TPR for that attack
    family), seed-paired, per issue spec."""
    sub = df[df["experiment"] == "E2"]
    if len(sub) == 0:
        print("  [Table 2] No E2 data yet -- skipping.")
        return None

    aggregators = sorted(sub["aggregator"].dropna().unique())
    attacks = sorted(sub["attack_type"].dropna().unique())
    results = []
    for attack in attacks:
        attack_sub = sub[sub["attack_type"] == attack]
        agg_means = {}
        agg_by_seed = {}
        for agg in aggregators:
            cell = attack_sub[attack_sub["aggregator"] == agg]
            agg_by_seed[agg] = dict(zip(cell["seed"], cell["byzantine_tpr"]))
            m = cell["byzantine_tpr"].mean()
            agg_means[agg] = m if m == m else -1.0

        non_cal = [a for a in aggregators if a != "calibrated_krum"]
        if not non_cal:
            continue
        best_baseline = max(non_cal, key=lambda a: agg_means.get(a, -1.0))

        key = f"table2/{attack}/calibrated_vs_{best_baseline}"
        test_res = None
        if "calibrated_krum" in agg_by_seed:
            test_res = paired_ttest_cohend(
                agg_by_seed["calibrated_krum"], agg_by_seed[best_baseline],
                registry, key,
            )
        results.append((attack, best_baseline, agg_means, key, test_res))

    if mode == "stats":
        return None

    rows = []
    for attack, best_baseline, agg_means, key, test_res in results:
        for agg in aggregators:
            cell = sub[(sub["attack_type"] == attack) & (sub["aggregator"] == agg)]
            tpr_mean, tpr_sd, *_ , n = mean_sd_ci(cell["byzantine_tpr"])
            fpr_mean, fpr_sd, *_ , _n = mean_sd_ci(cell["honest_fpr"])
            f1_mean, f1_sd, *_ , _n2 = mean_sd_ci(cell["test_f1_macro"])

