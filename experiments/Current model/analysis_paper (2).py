def fmt(x):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    if isinstance(x, (int, np.integer)):
        return str(int(x))
    return ANALYSIS_FLOAT_FMT.format(float(x))


def latex_escape(s):
    return str(s).replace("_", r"\_").replace("%", r"\%")


def write_latex_table(path, caption, label, header_cols, rows, notes=None):
    """rows: list[list[str]] -- already-formatted cell strings (use
    fmt()/stars_for() before calling this). Writes a standalone
    tabular + caption/label block, one \\begin{table} per file, so
    \\input{tables/table_N} drops straight into a paper body."""
    n_cols = len(header_cols)
    lines = []
    lines.append(r"\begin{table}[t]")
    lines.append(r"\centering")
    lines.append(r"\caption{" + latex_escape(caption) + "}")
    lines.append(r"\label{" + label + "}")
    lines.append(r"\begin{tabular}{" + "l" * n_cols + "}")
    lines.append(r"\toprule")
    lines.append(" & ".join(latex_escape(c) for c in header_cols) + r" \\")
    lines.append(r"\midrule")
    for row in rows:
        lines.append(" & ".join(str(c) for c in row) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    if notes:
        lines.append(r"\vspace{2pt}")
        lines.append(r"\footnotesize " + latex_escape(notes))
    lines.append(r"\end{table}")
    lines.append("")  # trailing newline, stable across platforms

    text = "\n".join(lines)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:  # DETERMINISM: fixed line ending
        f.write(text)
    return text


