class TestRegistry:
    """Issue 5 Task 4's global test counter + Bonferroni-correction
    machinery (see module docstring's "SIGNIFICANCE POLICY" section for
    the two-pass rationale). Every formal hypothesis test in this
    script (paired t-tests, ANOVA omnibus + Tukey HSD pairwise) is
    registered here via .register(); after PASS 1 has run every table
    builder once, .n_tests tells every builder in PASS 2 whether
    Bonferroni applies and at what denominator."""

    def __init__(self):
        self.records = []  # list of dicts: {key, raw_p, kind}

    def register(self, key, raw_p, kind):
        # IDEMPOTENT by key: table builders are called ONCE in PASS 1
        # ("stats" mode, to populate this registry / discover n_tests)
        # and AGAIN in PASS 2 ("render" mode) -- re-running the exact
        # same test computation with the same key both times. Without
        # this idempotency check, PASS 2's re-registration would
        # silently double (or triple, once other builders' PASS-2 calls
        # interleave) every count, corrupting self.n_tests / the
        # Bonferroni denominator mid-render depending on which builder
        # happens to read it first -- caught via the determinism test
        # at the bottom of this file (table_2's own caption text, which
        # embeds registry.n_tests, differed between two runs before
        # this fix).
        for rec in self.records:
            if rec["key"] == key:
                rec["raw_p"] = raw_p  # same computation -> same value;
                                        # update in place, no new count
                return raw_p
        self.records.append({"key": key, "raw_p": raw_p, "kind": kind})
        return raw_p

    @property
    def n_tests(self):
        return len(self.records)

    @property
    def bonferroni_denominator(self):
        return self.n_tests if self.n_tests > BONFERRONI_TRIGGER_N_TESTS else 1

    def corrected_p(self, key):
        for rec in self.records:
            if rec["key"] == key:
                p = rec["raw_p"] * self.bonferroni_denominator
                return min(p, 1.0)
        raise KeyError(f"No test registered under key {key!r}")

    def reset(self):
        self.records = []


def mean_sd_ci(values, confidence=CONFIDENCE_LEVEL):
    """Sample mean, sample SD (ddof=1), and a two-sided t-distribution
    confidence interval. Returns (mean, sd, ci_low, ci_high, n); NaNs
    for n<2 (can't estimate spread from a single seed -- report the
    single value honestly rather than a fabricated zero-width CI)."""
    arr = np.asarray([v for v in values if v is not None and not
                       (isinstance(v, float) and math.isnan(v))], dtype=float)
    n = len(arr)
    if n == 0:
        return float("nan"), float("nan"), float("nan"), float("nan"), 0
    mean = float(arr.mean())
    if n < 2:
        return mean, float("nan"), float("nan"), float("nan"), n
    sd = float(arr.std(ddof=1))
    sem = sd / math.sqrt(n)
    tcrit = scipy_stats.t.ppf((1 + confidence) / 2.0, df=n - 1)
    return mean, sd, mean - tcrit * sem, mean + tcrit * sem, n


def paired_ttest_cohend(a_by_seed, b_by_seed, registry, key):
    """Seed-paired two-tailed t-test + Cohen's d (paired form:
    d = mean(diff) / sd(diff)). a_by_seed/b_by_seed: {seed: value}
    dicts -- only seeds present in BOTH are used (issue spec: "seed-
    paired"); a seed missing from either arm is dropped with a printed
    note rather than silently biasing the pairing. Registers the raw
    p-value under `key` in `registry` (PASS 1) or reads the already-
    corrected p back out (PASS 2) -- see TestRegistry's docstring.
    Returns dict with t, raw_p, cohens_d, n_pairs, and (once PASS 2 has
    run) corrected_p / stars.
    """
    common_seeds = sorted(set(a_by_seed) & set(b_by_seed))
    dropped = sorted((set(a_by_seed) | set(b_by_seed)) - set(common_seeds))
    if dropped:
        print(f"    [{key}] dropping seed(s) {dropped} -- present in only "
              f"one arm of the paired comparison.")
    if len(common_seeds) < 2:
        print(f"    [{key}] fewer than 2 paired seeds available -- "
              f"cannot run a paired t-test.")
        registry.register(key, float("nan"), "paired_t")
        return {"t": float("nan"), "raw_p": float("nan"),
                "cohens_d": float("nan"), "n_pairs": len(common_seeds)}

    a = np.array([a_by_seed[s] for s in common_seeds], dtype=float)
    b = np.array([b_by_seed[s] for s in common_seeds], dtype=float)
    diff = a - b
    t_stat, raw_p = scipy_stats.ttest_rel(a, b)
    sd_diff = diff.std(ddof=1)
    cohens_d = float(diff.mean() / sd_diff) if sd_diff > 0 else float("nan")

    registry.register(key, float(raw_p), "paired_t")
    return {"t": float(t_stat), "raw_p": float(raw_p),
            "cohens_d": cohens_d, "n_pairs": len(common_seeds)}


def anova_tukey(groups, registry, key_prefix):
    """One-way ANOVA + Tukey HSD post-hoc across >=2 groups.
    `groups`: {label: [values]} (unequal n allowed). Registers the
    ANOVA omnibus p-value under f"{key_prefix}/omnibus" and each
    pairwise Tukey comparison under f"{key_prefix}/{a}_vs_{b}".
    Returns dict with f_stat, omnibus_raw_p, and a list of pairwise
    dicts {a, b, mean_diff, raw_p}."""
    labels = sorted(groups)  # DETERMINISM: fixed group order
    samples = [np.asarray(groups[l], dtype=float) for l in labels]
    samples = [s[~np.isnan(s)] for s in samples]
    usable = [(l, s) for l, s in zip(labels, samples) if len(s) >= 2]
    if len(usable) < 2:
        print(f"    [{key_prefix}] fewer than 2 usable groups (>=2 obs "
              f"each) -- cannot run ANOVA/Tukey.")
        registry.register(f"{key_prefix}/omnibus", float("nan"), "anova")
        return {"f_stat": float("nan"), "omnibus_raw_p": float("nan"),
                "pairwise": []}

    labels_u = [l for l, _ in usable]
    samples_u = [s for _, s in usable]
    f_stat, omnibus_p = scipy_stats.f_oneway(*samples_u)
    registry.register(f"{key_prefix}/omnibus", float(omnibus_p), "anova")

    pairwise = []
    if _HAVE_STATSMODELS:
        all_vals = np.concatenate(samples_u)
        all_labels = np.concatenate(
            [[l] * len(s) for l, s in zip(labels_u, samples_u)])
        tukey_res = pairwise_tukeyhsd(all_vals, all_labels, alpha=0.05)
        for row in tukey_res.summary().data[1:]:
            g1, g2, meandiff, p_adj, lo, hi, reject = row
            # statsmodels already applies its OWN internal Tukey
            # correction for the family of pairwise comparisons; we
            # register p_adj as this test's "raw" p and let this
            # script's OWN Bonferroni layer (across ALL tests in the
            # whole paper, not just this one ANOVA's pairwise family)
            # apply on top if the global count exceeds 10 -- documented
            # double-correction, conservative by construction, never
            # anti-conservative.
            key = f"{key_prefix}/{g1}_vs_{g2}"
            registry.register(key, float(p_adj), "tukey")
            pairwise.append({"a": g1, "b": g2, "mean_diff": float(meandiff),
                              "raw_p": float(p_adj), "key": key})
    else:
        print(f"    [{key_prefix}] statsmodels not available -- falling "
              f"back to manual Tukey HSD via scipy.stats.studentized_range.")
        pairwise = _manual_tukey_hsd(labels_u, samples_u, registry, key_prefix)

    return {"f_stat": float(f_stat), "omnibus_raw_p": float(omnibus_p),
            "pairwise": pairwise}


def _manual_tukey_hsd(labels, samples, registry, key_prefix):
    """Fallback Tukey HSD (equal-variance assumption, standard
    textbook form) for environments without statsmodels installed.
    q = |mean_i - mean_j| / sqrt(MSE/2 * (1/n_i + 1/n_j))
    p = 1 - studentized_range.cdf(q, k, df_within)
    """
    k = len(labels)
    n_total = sum(len(s) for s in samples)
    df_within = n_total - k
    grand_means = [s.mean() for s in samples]
    ss_within = sum(((s - s.mean()) ** 2).sum() for s in samples)
    mse = ss_within / df_within if df_within > 0 else float("nan")

    pairwise = []
    for i in range(k):
        for j in range(i + 1, k):
            ni, nj = len(samples[i]), len(samples[j])
            mean_diff = grand_means[i] - grand_means[j]
            se = math.sqrt(mse / 2.0 * (1.0 / ni + 1.0 / nj)) if mse == mse else float("nan")
            q_stat = abs(mean_diff) / se if se and se > 0 else float("nan")
            p = (1.0 - scipy_stats.studentized_range.cdf(q_stat, k, df_within)
                 if q_stat == q_stat and df_within > 0 else float("nan"))
            key = f"{key_prefix}/{labels[i]}_vs_{labels[j]}"
            registry.register(key, float(p), "tukey_manual")
            pairwise.append({"a": labels[i], "b": labels[j],
                              "mean_diff": float(mean_diff), "raw_p": float(p),
                              "key": key})
    return pairwise


def stars_for(corrected_p):
    if corrected_p != corrected_p:  # NaN
        return ""
    if corrected_p < 0.001:
        return "***"
    if corrected_p < 0.01:
        return "**"
    if corrected_p < 0.05:
        return "*"
    return ""


