def figure_7_composite(df, runs, figures_dir):
    """4-panel Q1-rigor composite: (a) FedProx mu sensitivity,
    (b) MAD-k Honest-FPR sweep [reconstructed post-hoc from raw Krum
    scores -- see the docstring note below], (c) Byzantine fraction f
    sweep, (d) E7 cross-dataset directionality."""
    fig, axes = plt.subplots(2, 2, figsize=(10, 8))

    # (a) FedProx mu sensitivity -- E1
    ax = axes[0, 0]
    e1 = df[df["experiment"] == "E1"]
    if len(e1):
        for agg in sorted(e1["aggregator"].dropna().unique()):
            agg_sub = e1[e1["aggregator"] == agg]
            xs, ys = [], []
            for mu in FEDPROX_MU_SWEEP:
                cell = agg_sub[np.isclose(agg_sub["fedprox_mu"], mu)]
                if len(cell) == 0:
                    continue
                mean, *_ = mean_sd_ci(cell["test_f1_macro"])
                xs.append(mu)
                ys.append(mean)
            if xs:
                ax.plot(xs, ys, marker="o", label=agg, markersize=3)
        ax.legend(fontsize=6)
    ax.set_xlabel(r"FedProx $\mu$")
    ax.set_ylabel("Macro-F1")
    ax.set_title("(a) FedProx $\\mu$ sensitivity")

    # (b) MAD-k Honest-FPR sweep -- reconstructed post-hoc from raw
    # per-client Krum scores using the median + k*MAD family formula
    # (see defences/byzantine.py:estimate_norm_guard_tau's docstring
    # for the same formula applied to norms; here applied to
    # raw_krum_score). THIS IS A DOCUMENTED APPROXIMATION: it assumes
    # Calibrated/Adaptive Krum's actual selection rule for a given k is
    # exactly "exclude any client whose raw_krum_score exceeds
    # median + k*MAD" -- confirm this matches defences/krum.py's real
    # formula before trusting this panel; if the real rule differs
    # (e.g. rank-based top-m selection rather than a MAD threshold),
    # re-run E4's actual MAD-k sweep at each k value instead of relying
    # on this reconstruction.
    ax = axes[0, 1]
    e4_runs = [r for r in runs if r.experiment == "E4" and r.krum_rows is not None]
    if e4_runs:
        for agg in sorted({r.aggregator for r in e4_runs}):
            xs, ys = [], []
            for k in MAD_K_SWEEP:
                fprs = []
                for r in e4_runs:
                    if r.aggregator != agg:
                        continue
                    kdf = r.krum_rows
                    kdf = kdf[kdf["classification"] != "N/A"]
                    if len(kdf) == 0:
                        continue
                    last_round = kdf["round_id"].max()
                    kdf = kdf[kdf["round_id"] == last_round]
                    scores = kdf["raw_krum_score"].values
                    median = np.median(scores)
                    mad = np.median(np.abs(scores - median))
                    threshold = median + k * mad
                    excluded = kdf["raw_krum_score"] > threshold
                    honest_mask = kdf["ground_truth_client_label"] == "honest"
                    if honest_mask.sum() == 0:
                        continue
                    fpr = (excluded & honest_mask).sum() / honest_mask.sum()
                    fprs.append(fpr)
                if fprs:
                    xs.append(k)
                    ys.append(np.mean(fprs))
            if xs:
                ax.plot(xs, ys, marker="o", label=agg, markersize=3)
        ax.legend(fontsize=6)
    ax.set_xlabel("MAD-$k$")
    ax.set_ylabel("Honest FPR (reconstructed)")
    ax.set_title("(b) MAD-$k$ sensitivity [post-hoc reconstruction]")

    # (c) Byzantine fraction f sweep -- E5
    ax = axes[1, 0]
    e5 = df[df["experiment"] == "E5"]
    if len(e5):
        for agg in sorted(e5["aggregator"].dropna().unique()):
            agg_sub = e5[e5["aggregator"] == agg]
            xs, tprs, fprs = [], [], []
            for f in BYZANTINE_F_SWEEP:
                cell = agg_sub[agg_sub["num_byzantine"] == f]
                if len(cell) == 0:
                    continue
                tpr_mean, *_ = mean_sd_ci(cell["byzantine_tpr"])
                fpr_mean, *_ = mean_sd_ci(cell["honest_fpr"])
                xs.append(f)
                tprs.append(tpr_mean)
                fprs.append(fpr_mean)
            if xs:
                ax.plot(xs, tprs, marker="o", linestyle="-",
                        label=f"{agg} TPR", markersize=3)
                ax.plot(xs, fprs, marker="s", linestyle="--",
                        label=f"{agg} FPR", markersize=3)
        ax.legend(fontsize=5)
    ax.set_xlabel("Byzantine client count $f$ (of 10)")
    ax.set_ylabel("Rate")
    ax.set_title("(c) Byzantine fraction sweep")

    # (d) E7 cross-dataset directionality
    ax = axes[1, 1]
    e7 = df[df["experiment"] == "E7"]
    if len(e7):
        for agg in sorted(e7["aggregator"].dropna().unique()):
            agg_sub = e7[e7["aggregator"] == agg]
            xs, ys = [], []
            for alpha in sorted(agg_sub["alpha"].dropna().unique(), reverse=True):
                cell = agg_sub[agg_sub["alpha"] == alpha]
                mean, *_ = mean_sd_ci(cell["honest_fpr"])
                xs.append(alpha)
                ys.append(mean)
            if xs:
                ax.plot(xs, ys, marker="o", label=agg, markersize=3)
        ax.legend(fontsize=6)
        ax.invert_xaxis()
    ax.set_xlabel(r"$\alpha$")
    ax.set_ylabel("Honest FPR")
    ax.set_title("(d) E7 cross-dataset directionality")

    fig.suptitle("Figure 7: Q1-rigor composite")
    fig.tight_layout()
    path = os.path.join(figures_dir, "figure_7_composite.png")
    _save_fig(fig, path)
    return path


