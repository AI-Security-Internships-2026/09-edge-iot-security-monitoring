"""
Issue 5 Task 4 -- scripts/analysis_paper.py

Produces paper-ready Tables 1-6 (LaTeX) and Figures 1-7 (300 DPI PNGs)
from the 5-seed result directory tree written by main.py + the Task 3
campaign runners, automatically and reproducibly (byte-identical output
on repeated runs against the same input data -- see "DETERMINISM" below).

------------------------------------------------------------------------
INPUT LAYOUT
------------------------------------------------------------------------
    experiments/results/<E#>/<seed>/<condition_tag>/
        experiment_config_<TAG>.json        -- run manifest (Task 4 dep:
                                                includes "aggregator",
                                                added in Issue 5 Task 1's
                                                main.py patch -- see that
                                                patch's _resolve_
                                                aggregator_canonical())
        results_<TAG>_FINAL_TEST.csv        -- one row: test_f1_macro +
                                                per-class f1/recall/aucpr
        dp_final_epsilon_<TAG>.json         -- final_total_epsilon per
                                                client (USE_DP runs only)
        per_client_krum_scores_<TAG>.csv    -- one row per (round,
                                                client): raw_krum_score,
                                                ground_truth, TP/FP/TN/FN
                                                classification -- SOURCE
                                                OF TRUTH for Byzantine
                                                TPR / Honest FPR and for
                                                Figures 2, 6, 7b.
        results_<TAG>.csv                   -- per-round per-client
                                                training log (loss/acc/
                                                per-class F1 timeline)

This script does NOT assume anything about condition_tag naming -- every
grouping variable (aggregator, alpha, attack_type, target epsilon, MAD-k,
FedProx mu, Byzantine fraction f) is read from experiment_config_<TAG>
.json, never parsed out of a directory name, since Task 3's runner
scripts are free to name condition_tag directories however is convenient
for them.

------------------------------------------------------------------------
DETERMINISM
------------------------------------------------------------------------
- No wall-clock timestamps, hostnames, or PIDs are written into any
  table or figure.
- Every groupby/sort operation uses an explicit, stable sort key before
  iteration or output -- Python dict/set iteration order is NEVER relied
  upon for anything that affects output content or row order.
- All floats are formatted with a fixed precision string (ANALYSIS_FLOAT_FMT)
  before being written to LaTeX -- never str(float) or an f-string without
  an explicit format spec, which can vary by platform/locale.
- matplotlib uses the non-interactive "Agg" backend explicitly, and every
  figure is saved with a fixed dpi, fixed figsize, and no autogenerated
  timestamps/watermarks.
- No randomness anywhere in this file: every statistic here (t-CI, paired
  t-test, ANOVA, Tukey HSD, Bonferroni) is closed-form, not bootstrapped.
This is verified by test_determinism() at the bottom of this file, which
runs the full pipeline twice against the same input directory and diffs
every output byte-for-byte.

------------------------------------------------------------------------
SIGNIFICANCE POLICY (issue requirement: "no significance manufacture")
------------------------------------------------------------------------
- Every formal hypothesis test performed anywhere in this script is
  counted in a single global counter, GLOBAL_TEST_COUNTER. If that
  counter exceeds 10 by the time all tables are built, Bonferroni
  correction (alpha / n_tests) is applied to EVERY p-value used for a
  significance superscript -- not just the ones computed after the
  10th test -- because "which p-values get corrected" must not depend
  on table-generation order.
- If a corrected p-value is > 0.05, the table cell gets NO significance
  superscript and, in Table 2/4's notes column, an explicit "NS
  (directional trend only)" annotation -- never silently rounded away,
  never a manufactured "*" for a borderline value.
- Two-pass design: PASS 1 runs every table builder in "stats-only" mode
  to populate GLOBAL_TEST_COUNTER and cache every p-value; PASS 2 (after
  the Bonferroni denominator is known) actually renders the LaTeX with
  correct superscripts. This is what makes the Bonferroni correction
  apply uniformly regardless of table order (see run_all() below).
"""

