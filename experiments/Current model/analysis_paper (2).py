def select_rare_classes(class_names, rarest_n=None):
    """Returns the subset of RARE_CLASS_NAMES actually present in this
    data's class_names (a single run/model_type only ever has ONE of
    network's or application's label sets, so at most 3 of the 5 named
    classes will be present for any one model_type -- that's expected,
    not a bug: filter to the intersection rather than padding or
    erroring). Order follows RARE_CLASS_NAMES, not alphabetical.

    rarest_n, if given, caps the result at that many classes (kept for
    call-site/CLI-flag compatibility with the old rarest_n-based
    signature) -- but never adds classes beyond RARE_CLASS_NAMES to
    reach that count; it can only truncate.
    """
    present = [c for c in RARE_CLASS_NAMES if c in class_names]
    if not present:
        print(f"  WARNING: none of RARE_CLASS_NAMES {RARE_CLASS_NAMES} "
              f"found in this data's class list {class_names} -- check "
              f"that class_names came from a run with test_f1_<name> "
              f"columns using data_loader.py's real label spelling.")
    return present[:rarest_n] if rarest_n else present


def krum_tpr_fpr(krum_df, rounds="last"):
    """Byzantine TPR / Honest FPR from a per_client_krum_scores
    DataFrame. rounds='last' uses only the final logged round
    (converged-model view, used for headline Tables 1-4); rounds='all'
    averages over every logged round (used for Task 2-style sanity
    checks). Returns (tpr, fpr) or (nan, nan) if the run didn't have
    Krum-family detection active (classification == 'N/A' throughout).
    """
    if krum_df is None or len(krum_df) == 0:
        return float("nan"), float("nan")
    df = krum_df[krum_df["classification"] != "N/A"]
    if len(df) == 0:
        return float("nan"), float("nan")
    if rounds == "last":
        last_round = df["round_id"].max()
        df = df[df["round_id"] == last_round]

    byz = df[df["ground_truth_client_label"] == "byzantine"]
    honest = df[df["ground_truth_client_label"] == "honest"]

    tpr = (byz["classification"] == "TP").sum() / len(byz) if len(byz) else float("nan")
    fpr = (honest["classification"] == "FP").sum() / len(honest) if len(honest) else float("nan")
    return float(tpr), float(fpr)


def build_master_dataframe(runs):
    """One row per run, every grouping/metric column flattened out.
    This is the single table every Table/Figure builder below reads
    from -- no builder re-parses raw run directories itself."""
    rows = []
    for r in runs:
        tpr, fpr = krum_tpr_fpr(r.krum_rows, rounds="last")
        row = {
            "experiment": r.experiment,
            "seed": r.seed,
            "condition_tag": r.condition_tag,
            "aggregator": r.aggregator,
            "alpha": r.alpha,
            "attack_type": r.attack_type if r.byzantine_attack else "none",
            "byzantine_attack": bool(r.byzantine_attack),
            "num_byzantine": r.num_byzantine,
            "target_epsilon": r.target_epsilon,
            "use_dp": bool(r.use_dp),
            "final_total_epsilon": r.final_total_epsilon_mean,
            "fedprox_mu": r.fedprox_mu,
            "krum_k": r.krum_k,
            "test_f1_macro": r.final_test.get("test_f1_macro"),
            "test_accuracy": r.final_test.get("test_accuracy"),
            "byzantine_tpr": tpr,
            "honest_fpr": fpr,
            "run_dir": r.run_dir,
        }
        # E8-only runtime columns, if this run has them (see
        # load_runtime()'s fix docstring) -- absent (not NaN-filled)
        # for non-E8 runs, so table_5_runtime_overhead()'s own
        # `required - set(sub.columns)` check still correctly detects
        # genuinely missing data on old/incompatible result trees.
        for k in ("latency_sec_per_round", "peak_ram_mb", "comms_bytes"):
            if k in r.runtime:
                row[k] = r.runtime[k]
        # Per-class metrics, carried through with their original column
        # names (test_f1_<class>, test_recall_<class>, test_aucpr_<class>)
        # so Table 5-equivalent / Task 5's rare-class table can pivot on
        # them directly without re-deriving class names per row.
        for k, v in r.final_test.items():
            if k.startswith(("test_f1_", "test_recall_", "test_aucpr_")) and \
                    k != "test_f1_macro":
                row[k] = v
        rows.append(row)

    df = pd.DataFrame(rows)
    if len(df):
        df = df.sort_values(
            ["experiment", "aggregator", "alpha", "attack_type",
             "target_epsilon", "seed"],
            na_position="last",
        ).reset_index(drop=True)
    return df


